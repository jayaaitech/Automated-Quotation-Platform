"""
RFQ AI System - Export Router
Handles the generation and downloading of PDF quotations 
based on the structured data generated by the AI pipeline.
"""

import io
import logging
from fastapi import APIRouter, Body, HTTPException
from fastapi.responses import StreamingResponse
from fpdf import FPDF

# Set up logging for debugging
logger = logging.getLogger(__name__)

# Define the router with a prefix so this route starts with /export
router = APIRouter(prefix="/export", tags=["Export & Download"])

# ==========================================================
# 📄 GENERATE & DOWNLOAD PDF QUOTE
# ==========================================================
@router.post("/quote-pdf", summary="Download Quotation as PDF")
async def export_quote_pdf(quote_data: dict = Body(...)):
    """
    Takes the structured Quote JSON (generated by the chat UI) 
    and converts it into a professional, downloadable PDF document.
    """
    try:
        # Extract metadata safely
        meta = quote_data.get("metadata", {})
        quote_id = meta.get("quote_id", "UNKNOWN")
        date_str = meta.get("generated_at", "N/A")[:10] # Grab just the YYYY-MM-DD
        
        logger.info(f"Generating PDF for Quote ID: {quote_id}")

        # 1. Initialize PDF document
        pdf = FPDF()
        pdf.add_page()
        
        # 2. Add Company / Document Header
        pdf.set_font("Arial", "B", 16)
        pdf.cell(0, 10, "OFFICIAL ENGINEERING QUOTATION", ln=True, align="C")
        
        # 3. Add Metadata (Quote ID & Date) aligned to the right
        pdf.set_font("Arial", "", 10)
        pdf.cell(0, 10, f"Quote ID: {quote_id}", ln=True, align="R")
        pdf.cell(0, 5, f"Date: {date_str}", ln=True, align="R")
        pdf.ln(10) # Add some vertical space

        # 4. Table Header Row (With light blue background)
        pdf.set_fill_color(200, 220, 255)
        pdf.set_font("Arial", "B", 10)
        pdf.cell(100, 10, "Item Description", border=1, align="C", fill=True)
        pdf.cell(30, 10, "Qty", border=1, align="C", fill=True)
        pdf.cell(30, 10, "Unit ($)", border=1, align="C", fill=True)
        # Use ln=True on the last cell to move to the next row
        pdf.cell(30, 10, "Total ($)", border=1, ln=True, align="C", fill=True)

        # 5. Populate Table with Line Items
        pdf.set_font("Arial", "", 9)
        for item in quote_data.get("line_items", []):
            # Truncate extremely long item names so they don't break the table UI
            name = str(item.get("item_name", "Unknown Item"))[:50] 
            qty = str(item.get("quantity", 0))
            unit_cost = float(item.get("unit_cost", 0.0))
            total_cost = float(item.get("total_cost", 0.0))
            
            pdf.cell(100, 8, name, border=1)
            pdf.cell(30, 8, qty, border=1, align="C")
            pdf.cell(30, 8, f"{unit_cost:.2f}", border=1, align="R")
            pdf.cell(30, 8, f"{total_cost:.2f}", border=1, ln=True, align="R")

        pdf.ln(10) # Add space before the summary

        # 6. Summary & Totals Table
        pdf.set_font("Arial", "B", 10)
        summary = quote_data.get("summary", {})
        mat_subtotal = float(summary.get("material_subtotal", 0.0))
        labor = float(summary.get("labor_cost", 0.0))
        grand_total = float(summary.get("total_quote", 0.0))
        
        # Material Subtotal
        pdf.cell(130, 8, "Material Subtotal:", border=0, align="R")
        pdf.cell(60, 8, f"${mat_subtotal:.2f}", border=1, ln=True, align="R")
        
        # Labor Cost
        pdf.cell(130, 8, "Labor & Design:", border=0, align="R")
        pdf.cell(60, 8, f"${labor:.2f}", border=1, ln=True, align="R")

        # Grand Total (With light orange background to stand out)
        pdf.set_fill_color(255, 230, 200)
        pdf.cell(130, 10, "TOTAL QUOTATION:", border=0, align="R")
        pdf.cell(60, 10, f"${grand_total:.2f}", border=1, ln=True, align="R", fill=True)

        # 7. Output to Byte Stream
        # Request the PDF as a string/byte output
        pdf_out = pdf.output(dest='S')
        
        # If using legacy fpdf, it returns a string. We must encode it to bytes.
        if isinstance(pdf_out, str):
            pdf_bytes = pdf_out.encode('latin-1')
        else:
            # If using fpdf2, it already returns bytes
            pdf_bytes = bytes(pdf_out) 
            
        pdf_stream = io.BytesIO(pdf_bytes)
        
        # 8. Return as a downloadable file stream
        return StreamingResponse(
            pdf_stream,
            media_type="application/pdf",
            headers={"Content-Disposition": f"attachment; filename=Quote_{quote_id}.pdf"}
        )
    except Exception as e:
        logger.exception("❌ PDF Generation failed")
        raise HTTPException(
            status_code=500, 
            detail=f"Failed to generate PDF: {str(e)}"
        )